#ifndef SRC_MY_GRAPH_ALGORITHMS_H_
#define SRC_MY_GRAPH_ALGORITHMS_H_

#include <string.h>

#include "heap.h"
#include "queue/my_queue.h"
#include "my_graph.h"
#include "stack/my_stack.h"

// Параметры для алгоритма муравьиной колонии (ACO)
#define ACO_ALPHA 1.0       // Важность феромона
#define ACO_BETA 2.0        // Важность эвристики (обратное расстояние)
#define ACO_RHO 0.5         // Скорость испарения феромона (0.0 - 1.0)
#define ACO_Q 100.0         // Константа выделения феромона
#define NUM_ANTS 20         // Количество муравьёв за итерацию
#define NUM_ITERATIONS 100  // Количество итераций алгоритма

/**
 * @brief Результат решения задачи коммивояжера (TSP).
 */
typedef struct {
  int* vertices;    ///< Массив с искомым маршрутом (порядок обхода вершин).
  double distance;  ///< Общая длина (вес) этого маршрута.
} tsm_result;

/**
 * @brief Поиск в глубину (Depth-First Search, DFS).
 *
 * @param graph Указатель на исходный граф.
 * @param start_vertex Индекс начальной вершины для обхода.
 * @return Динамически выделенный массив индексов посещенных вершин.
 *         Возвращает NULL, если граф равен NULL или start_vertex некорректен.
 * @note Вызывающая сторона обязана освободить память, выделенную под
 *       возвращаемый массив, с помощью free().
 */
unsigned* my_depth_first_search(my_graph* graph, int start_vertex);

/**
 * @brief Поиск в ширину (Breadth-First Search, BFS).
 *
 * @param graph Указатель на исходный граф.
 * @param start_vertex Индекс начальной вершины для обхода.
 * @return Динамически выделенный массив индексов посещенных вершин.
 *         Возвращает NULL, если граф равен NULL или start_vertex некорректен.
 * @note Вызывающая сторона обязана освободить память, выделенную под
 *       возвращаемый массив, с помощью free().
 */
unsigned* my_breadth_first_search(my_graph* graph, int start_vertex);

/**
 * @brief Поиск кратчайшего пути между двумя заданными вершинами
 *        (алгоритм Дейкстры).
 *
 * @param graph Указатель на исходный граф.
 * @param vertex1 Индекс начальной вершины.
 * @param vertex2 Индекс конечной вершины.
 * @return Длина кратчайшего пути. Возвращает -1, если путь не существует,
 *         или если входные данные (graph, индексы вершин) некорректны.
 * @note Алгоритм корректно работает только с неотрицательными весами ребер.
 */
int get_shortest_path_between_vertices(const my_graph* graph, int vertex1,
                                       int vertex2);

/**
 * @brief Поиск кратчайших путей между всеми парами вершин
 *        (алгоритм Флойда-Уоршелла).
 *
 * @param g Указатель на исходный граф.
 * @return Двумерная матрица (N x N), где элемент [i][j] содержит длину
 *         кратчайшего пути от вершины i к вершине j.
 *         Возвращает NULL при ошибке выделения памяти или некорректном графе.
 * @note Вызывающая сторона обязана освободить память под матрицу
 *       (освободить каждый ряд, а затем сам массив указателей).
 */
int** get_shortest_paths_between_all_vertices(my_graph* g);

/**
 * @brief Поиск минимального остовного дерева (Minimum Spanning Tree)
 *        с помощью алгоритма Прима.
 *
 * @param g Указатель на исходный взвешенный неориентированный граф.
 * @return Указатель на новый граф (структуру my_graph), представляющий
 *         минимальное остовное дерево. Возвращает NULL при ошибке.
 * @note Алгоритм предназначен для связных графов. Если граф несвязный,
 *       функция вернет остовное дерево только для той компоненты связности,
 *       которая содержит вершину с индексом 0. Вызывающая сторона обязана
 *       освободить память возвращенного графа через my_graph_destroy().
 */
my_graph* get_least_spanning_tree(my_graph* g);

/**
 * @brief Приближенное решение задачи коммивояжера (Traveling Salesman Problem)
 *        с использованием алгоритма муравьиной колонии (Ant Colony
 * Optimization).
 *
 * @param g Указатель на исходный взвешенный неориентированный граф.
 * @return Структура tsm_result, содержащая найденный маршрут и его длину.
 *         В случае ошибки (NULL граф) возвращает структуру с vertices = NULL
 *         и distance = -1.0 (или 0.0, в зависимости от вашей реализации).
 * @note Поле vertices в возвращаемой структуре динамически выделяется.
 *       Вызывающая сторона обязана освободить его с помощью free().
 */
tsm_result solve_traveling_salesman_problem(my_graph* g);

#endif  // SRC_MY_GRAPH_ALGORITHMS_H_